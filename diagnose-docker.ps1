# Script de diagnostic de l'environnement Docker PAFA
# ????????????????????????????????????????????????????????????????????????

Write-Host "????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host " PAFA POC - Diagnostic de l'environnement Docker" -ForegroundColor Cyan
Write-Host "????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# ?? 1. Vérifier Docker ??????????????????????????????????????????????????
Write-Host "[1/6] Vérification de Docker Desktop..." -ForegroundColor Yellow

try {
    $dockerVersion = docker --version 2>&1
    if ($LASTEXITCODE -eq 0) {
        Write-Host "  ? Docker installé : $dockerVersion" -ForegroundColor Green
    } else {
        throw "Docker non accessible"
    }
} catch {
    Write-Host "  ? Docker Desktop n'est pas installé ou démarré" -ForegroundColor Red
    Write-Host "    ? Installez Docker Desktop : https://www.docker.com/products/docker-desktop/" -ForegroundColor Yellow
    exit 1
}

Write-Host ""

# ?? 2. Lister les conteneurs en cours ???????????????????????????????????
Write-Host "[2/6] Conteneurs Docker actuellement en cours..." -ForegroundColor Yellow

$containers = docker ps --format "table {{.Names}}\t{{.Status}}\t{{.Ports}}"
if ($containers) {
    Write-Host $containers -ForegroundColor Gray
} else {
    Write-Host "  ? Aucun conteneur en cours d'exécution" -ForegroundColor Gray
}

Write-Host ""

# ?? 3. Vérifier les fichiers docker-compose ?????????????????????????????
Write-Host "[3/6] Vérification des fichiers Docker Compose..." -ForegroundColor Yellow

$files = @(
    "docker-compose.yml",
    "docker-compose.psql.dev.yml"
)

foreach ($file in $files) {
    if (Test-Path $file) {
        Write-Host "  ? Trouvé : $file" -ForegroundColor Green
    } else {
        Write-Host "  ? MANQUANT : $file" -ForegroundColor Red
    }
}

Write-Host ""

# ?? 4. Vérifier le réseau Docker ????????????????????????????????????????
Write-Host "[4/6] Vérification du réseau Docker..." -ForegroundColor Yellow

$networks = docker network ls --format "{{.Name}}" | Select-String "pafa"
if ($networks) {
    Write-Host "  ? Réseau pafa_network existe" -ForegroundColor Green
    $networks | ForEach-Object { Write-Host "    - $_" -ForegroundColor Gray }
} else {
    Write-Host "  ? Réseau pafa_network sera créé au démarrage" -ForegroundColor Gray
}

Write-Host ""

# ?? 5. Vérifier les dossiers SFTP ???????????????????????????????????????
Write-Host "[5/6] Vérification des dossiers SFTP locaux..." -ForegroundColor Yellow

$sftpFolders = @("xoserve\upload", "xoserve\processed", "xoserve\failed")

foreach ($folder in $sftpFolders) {
    if (Test-Path $folder) {
        Write-Host "  ? Existe : $folder" -ForegroundColor Green
    } else {
        Write-Host "  ? MANQUANT : $folder" -ForegroundColor Red
        Write-Host "    ? Créez-le : New-Item -ItemType Directory -Path $folder -Force" -ForegroundColor Yellow
    }
}

Write-Host ""

# ?? 6. Diagnostiquer PostgreSQL ?????????????????????????????????????????
Write-Host "[6/6] Diagnostic PostgreSQL détaillé..." -ForegroundColor Yellow

# Chercher tous les conteneurs postgres
$postgresContainers = docker ps -a --filter "ancestor=postgres" --format "{{.Names}}\t{{.Status}}"
if (!$postgresContainers) {
    $postgresContainers = docker ps -a --format "{{.Names}}\t{{.Status}}" | Select-String "postgres|pafa_db|db"
}

if ($postgresContainers) {
    Write-Host "  Conteneurs PostgreSQL trouvés :" -ForegroundColor Gray
    $postgresContainers | ForEach-Object { Write-Host "    $_" -ForegroundColor Gray }
    
    # Tester chaque conteneur
    $postgresContainers | ForEach-Object {
        $containerName = ($_ -split '\t')[0]
        Write-Host ""
        Write-Host "  Test de connexion : $containerName" -ForegroundColor Cyan
        
        $pgReady = docker exec $containerName pg_isready -U postgres 2>&1
        if ($LASTEXITCODE -eq 0) {
            Write-Host "    ? $containerName répond" -ForegroundColor Green
            
            # Tester la base pafadb
            $dbExists = docker exec $containerName psql -U postgres -lqt 2>&1 | Select-String "pafadb"
            if ($dbExists) {
                Write-Host "    ? Base de données 'pafadb' existe" -ForegroundColor Green
            } else {
                Write-Host "    ? Base de données 'pafadb' n'existe pas" -ForegroundColor Yellow
                Write-Host "      ? Elle sera créée au premier démarrage de l'API" -ForegroundColor Gray
            }
        } else {
            Write-Host "    ? $containerName ne répond pas" -ForegroundColor Red
            Write-Host "      Logs :" -ForegroundColor Yellow
            docker logs --tail 20 $containerName | ForEach-Object { Write-Host "      $_" -ForegroundColor Gray }
        }
    }
} else {
    Write-Host "  ? Aucun conteneur PostgreSQL trouvé" -ForegroundColor Red
    Write-Host ""
    Write-Host "  ?? Diagnostic :" -ForegroundColor Yellow
    Write-Host "    1. Le fichier docker-compose.psql.dev.yml existe-t-il ?" -ForegroundColor Gray
    Write-Host "    2. Le service 'db' est-il défini dedans ?" -ForegroundColor Gray
    Write-Host "    3. Erreur au démarrage ? Vérifiez : docker-compose logs db" -ForegroundColor Gray
}

Write-Host ""

# ?? Recommandations ?????????????????????????????????????????????????????
Write-Host "????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host " ?? RECOMMANDATIONS" -ForegroundColor Cyan
Write-Host "????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

if (!$postgresContainers) {
    Write-Host "? PROBLÈME : PostgreSQL n'est pas démarré" -ForegroundColor Red
    Write-Host ""
    Write-Host "Solutions possibles :" -ForegroundColor Yellow
    Write-Host ""
    Write-Host "1??  Vérifier que docker-compose.psql.dev.yml existe et contient le service 'db'" -ForegroundColor White
    Write-Host "   ? Ouvrez le fichier et vérifiez la configuration" -ForegroundColor Gray
    Write-Host ""
    Write-Host "2??  Créer le réseau Docker manuellement :" -ForegroundColor White
    Write-Host "   docker network create pafa_network" -ForegroundColor Cyan
    Write-Host ""
    Write-Host "3??  Redémarrer Docker Compose :" -ForegroundColor White
    Write-Host "   docker-compose down -v" -ForegroundColor Cyan
    Write-Host "   docker-compose up -d" -ForegroundColor Cyan
    Write-Host ""
    Write-Host "4??  Voir les logs d'erreur :" -ForegroundColor White
    Write-Host "   docker-compose logs" -ForegroundColor Cyan
    Write-Host ""
} else {
    Write-Host "? PostgreSQL est configuré" -ForegroundColor Green
    Write-Host ""
    Write-Host "Si le script init-docker-env.ps1 échoue toujours :" -ForegroundColor Yellow
    Write-Host ""
    Write-Host "1??  Identifier le nom exact du conteneur PostgreSQL" -ForegroundColor White
    Write-Host "   ? D'après docker-compose.psql.dev.yml, c'est probablement 'pafa_postgres' ou 'db'" -ForegroundColor Gray
    Write-Host ""
    Write-Host "2??  Tester manuellement :" -ForegroundColor White
    Write-Host "   docker exec <nom_conteneur> pg_isready -U postgres" -ForegroundColor Cyan
    Write-Host ""
    Write-Host "3??  Si ça fonctionne, modifier init-docker-env.ps1 ligne 65 :" -ForegroundColor White
    Write-Host "   Remplacer 'db' par le nom exact du conteneur" -ForegroundColor Gray
    Write-Host ""
}

Write-Host "????????????????????????????????????????????????????????????" -ForegroundColor Cyan
